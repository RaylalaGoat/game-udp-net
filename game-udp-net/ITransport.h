// NetSession コンストラクタ引数 ITransport& のようにすると
// Winsock  UqpTransport
// Steam    SteamTransport(将来的に)
// NetSession を変更しないで差し替えられる
// =========================================================

namespace net
{
    //==============================================================
    // 送受信の層のインターフェース
    // NetSession はこのインターフェースだけを使う。
    //==============================================================
    class ITransport
    {
    public:

        // =========================================================
        // 仮想デストラクタ
        // =========================================================
        // デストラクタが virtual でないと、ITransport のデストラクタだけが呼ばれ、
        // UdpTransport のデストラクタ (ソケットを閉じる処理) が呼ばれない。

        virtual ~ITransport() = default;

        // =========================================================
        // 送信
        // =========================================================
        // 宛先に1個のパケットを送る。true は「OS に渡せた」の意味で、絶対に届くわけではない
        // virtual... = 0 「純粋仮想関数」

        // const NetAddress& to : 宛先
        // const void& data     : 送るバイト列の先頭 void* なのでどんな型の配列でも渡せる
        // int size             : 送るバイト数
        // → Winsock の sendto / recvfrom が int を使うため
        // 受信側でエラーを -1 で返すため
        // size_t ではなく int を使う

        virtual bool SendTo(const NetAddress& to, const void* data, int size) = 0;

        //----------------------------------------------------------
        // 受信
        //----------------------------------------------------------
        // 届いているパケットを1個読む。処理は止めない
        // 戻り値: >0 受信バイト数 / 0 何も届いていない / -1 エラー
        // 毎フレーム描画を続けないといけない 描画のため止まってはいけない
        // 何も届いていなければすぐ 0 を返す
        // 
        // 届いたら全部読む。1フレームが止まらないようにするため上限がある

        // 引数
        // void* buffer     : 受け取ったバイト列を書き込む(呼ぶ側が用意)
        // int bufferSize   : buffer の大きさ。  　　これより大きく書かない
        // NetAddress& from : 送り主の住所を書き込んで返す(出力用引数)

        // 戻り値 ( >0 / 0 / -1 )
        // 何も来ていない エラーの 2つを区別
        // NetSession が切断していいか判別できないため

        virtual int ReceiveFrom(void* buffer, int bufferSize, NetAddress& from) = 0;

    protected:

        //----------------------------------------------------------
        // 作成とコピーの制限
        //----------------------------------------------------------
        // 基底クラス専用

        ITransport() = default;

        // コピーを禁止
        // 1 スライシングの防止
        // 2 ソケットの二重所有の防止

        // 基底クラスでコピーを禁止すると派生クラス(UqpTransportでも自動コピーできなくなる)
        ITransport(const ITransport&) = delete;             // コピーコンストラクタ
        ITransport& operator=(const ITransport&) = delete;  // コピー演算子代入
    };

    // NetSession は ITransport を参照(ITransport&)を持つだけで 所持しない
    // のため transport は session より先に作り sessionより後に破棄される必要がある
}

#endif